import type { WordRow } from '../db/schema.js';

/** Vault folder of the server, relative to OBSIDIAN_DIR. Nothing outside it is ever touched. */
export const VAULT_ROOT = 'Vocab';

export type Book = { title: string; author: string | null };
export type StatusCounts = { learning: number; learned: number };

const MAX_NAME = 100;

/**
 * File name (without .md) for a word, book title or user name. Replaces path separators and
 * characters that are invalid in file names or break [[wiki links]], and refuses leading dots
 * so a name can never be `..` or a hidden file.
 */
export function noteName(raw: string): string {
  const name = raw
    .replace(/\p{Cc}/gu, ' ')
    .replace(/[/\\:*?"<>|[\]#^]/g, '-')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/^\.+/, '')
    .slice(0, MAX_NAME)
    .replace(/[\s.]+$/, '');
  return name || '_';
}

export const userFolder = (user: string) => `${VAULT_ROOT}/${noteName(user)}`;
const wordLink = (user: string, w: WordRow) => `[[${userFolder(user)}/Words/${noteName(w.word)}|${w.word}]]`;
const bookLink = (user: string, title: string) => `[[${userFolder(user)}/Books/${noteName(title)}]]`;

export function renderWordNote(w: WordRow, user: string): string {
  const front = [
    ['word', yamlPlain(w.word)],
    ['status', w.status],
    ['finnish', yamlQuoted(w.finnish)],
    ['ipa', yamlQuoted(w.ipa)],
    ['source', w.source],
    ['book', yamlQuoted(w.bookTitle && bookLink(user, w.bookTitle))],
    ['added', date(w.createdAt)],
    ['learned', date(w.learnedAt)],
    ['tags', `[vocab, vocab/${w.status}]`],
  ];
  const body = [
    `# ${oneLine(w.word)}`,
    `**Definition:** ${oneLine(w.definition)}`,
    w.example && `**Example:** ${oneLine(w.example)}`,
    w.finnish && `**Finnish:** ${oneLine(w.finnish)}`,
    w.notes?.trim() && `**Notes:** ${w.notes.trim()}`,
  ];
  return note(front, body);
}

export function renderBookNote(book: Book, words: WordRow[], user: string): string {
  const items = [...words]
    .sort((a, b) => a.word.localeCompare(b.word))
    .map((w) => `- ${wordLink(user, w)}${w.example ? `\n  - ${oneLine(w.example)}` : ''}`);
  return note(
    [
      ['title', yamlQuoted(book.title)],
      ['author', yamlQuoted(book.author)],
      ['tags', '[vocab/book]'],
    ],
    [`# ${oneLine(book.title)}`, items.join('\n')],
  );
}

export function renderIndex(user: string, counts: StatusCounts): string {
  const folder = userFolder(user);
  return note(
    [['tags', '[vocab]']],
    [
      `# Vocabulary: ${oneLine(user)}`,
      `- Learning: ${counts.learning}\n- Learned: ${counts.learned}\n- Total: ${counts.learning + counts.learned}`,
      'This folder is generated by the vocab server and overwritten on every export: edits made here are lost. ' +
        "Change words in the app; personal notes belong in a word's Notes field.",
      '`Words/` has one note per word, with `status`, `finnish`, `ipa`, `source`, `book`, `added` and `learned` ' +
        'in the frontmatter. `Books/` has one note per Kindle book linking its words. For example, with Dataview:',
      '```dataview\n' +
        `TABLE finnish, status, added FROM "${folder}/Words"\nWHERE status = "learning"\nSORT added DESC\n` +
        '```',
    ],
  );
}

function note(front: string[][], body: (string | null | undefined | false | '')[]): string {
  const yaml = front.map(([k, v]) => (v ? `${k}: ${v}` : `${k}:`)).join('\n');
  return `---\n${yaml}\n---\n${body.filter(Boolean).join('\n\n')}\n`;
}

const oneLine = (s: string) => s.replace(/\s*[\r\n]+\s*/g, ' ').trim();
const date = (iso: string | null) => (iso ? iso.slice(0, 10) : '');

/** Double-quoted YAML scalar (JSON strings are valid YAML), or empty for null. */
const yamlQuoted = (s: string | null) => (s ? JSON.stringify(oneLine(s)) : '');

/** Plain scalar when it is unambiguously a string, otherwise quoted. */
function yamlPlain(s: string): string {
  const safe = /^\p{L}[\p{L}\p{N} '.-]*$/u.test(s) && !/^(y|n|yes|no|true|false|on|off|null)$/i.test(s);
  return safe ? s : JSON.stringify(oneLine(s));
}
